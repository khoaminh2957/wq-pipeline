"""The formula arm: the model writes expressions directly, to test whether STRUCTURE is a lever.

Khoa's tick, 2026-09-19: run both arms from one GPU session and measure, rather than argue.

WHY THIS ARM EXISTS (measured 2026-09-19, and it is the strongest fact on the table):
  - `OPERATORS.md` is the RC-85 allowlist: **85 usable operators**, anything else is a 400 reject.
  - Across **18,796** simulated USA formulas we have ever used **20** of them.
  - Of the 1,025 rows that reached the Sharpe bar, `ts_mean` appears in 100 %, `group_rank` in 100 %,
    `multiply` in 71 %. The whole book is three operators.
  - `forge/compose.py` can only ever produce two shapes -- `multiply(A+, B+)` and
    `if_else(greater(B+, 0.5), A, 0)`. Everything else it varies is fields, windows and settings.
So 65 operators and every non-trivial skeleton are unexplored, and the mechanism arm cannot reach
them by construction. Whether that unexplored space contains anything is UNKNOWN; this arm measures it.

WHAT THIS ARM GIVES UP, stated before any result: a bare expression has no economics to grade, so
the 8 hard gates of `fetched/hypothesis_standard.md` do not apply. That is exactly the gap that
separated the hand-written library (2.6-3.2 % of rows at the bar) from the random-within-grammar
generator (0.1 %, 0 platform passes in 920 sims). To keep some of it, each formula carries a
one-line rationale, and `check_rationale` refuses one that names no counterparty.

Output is a plan JSON for `forge/runner.py --plan`, the same path the C11 and POW experiments used,
so the live planner and the allocator are untouched. RULE 1: nothing here simulates.
"""
